/// Writes the two files that only list other files.
///
/// - `lib/material_plus_ui.dart`, the barrel: every `mp_*.dart` under
///   `lib/src/components`, and the theme and types.
/// - `example/lib/demos/registry.dart`: every demo under
///   `example/lib/demos/<component>/`, keyed the way the documentation site
///   names it, `button-group/full-width`, which is also the React demo's path.
///
/// Generated rather than kept by hand because a hand-kept list of a hundred
/// and fifty components and six hundred demos is a list that falls behind, and
/// a component that is missing from the barrel is a component nobody can
/// import. Run it after adding a component or a demo:
///
/// ```bash
/// dart run tool/generate.dart
/// ```
///
/// `test/package/generated_test.dart` fails when either file is out of date.
library;

import 'dart:convert';
import 'dart:io';

Future<void> main(List<String> arguments) async {
  final bool check = arguments.contains('--check');
  final Directory root = File.fromUri(Platform.script).parent.parent;

  final List<(String, String)> outputs = <(String, String)>[
    for (final (String path, String source) in <(String, String)>[
      ('${root.path}/lib/material_plus_ui.dart', barrel(root)),
      ('${root.path}/example/lib/demos/registry.dart', registry(root)),
    ])
      (path, await formatted(path, source)),
  ];

  bool stale = false;

  for (final (String path, String contents) in outputs) {
    final File file = File(path);
    final String? current = file.existsSync() ? file.readAsStringSync() : null;

    if (current == contents) {
      continue;
    }

    stale = true;

    if (check) {
      stderr.writeln('$path is out of date. Run `dart run tool/generate.dart`.');
    } else {
      file.writeAsStringSync(contents);
      stdout.writeln('Wrote $path');
    }
  }

  if (check && stale) {
    exitCode = 1;
  }
}

/// [source] as `dart format` writes it for a file at [path], with the page width
/// configured beside that file, so the generated files pass the formatting check
/// as they are written. [source] unchanged if the formatter cannot be run.
Future<String> formatted(String path, String source) async {
  final Process process = await Process.start(Platform.resolvedExecutable, <String>[
    'format',
    '--output=show',
    '--stdin-name=$path',
  ]);
  final Future<String> output = process.stdout.transform(utf8.decoder).join();
  final Future<void> errors = process.stderr.drain<void>();

  process.stdin.write(source);
  await process.stdin.close();

  final String result = await output;
  await errors;

  return await process.exitCode == 0 ? result : source;
}

/// The public library: the theme, the vocabulary, and every component file.
String barrel(Directory root) {
  final Directory components = Directory('${root.path}/lib/src/components');
  final List<String> files =
      components
          .listSync(recursive: true)
          .whereType<File>()
          .where(
            (File file) => _basename(file.path).startsWith('mp_') && file.path.endsWith('.dart'),
          )
          .map((File file) => file.path.substring('${root.path}/lib/'.length))
          .toList()
        ..sort();

  final List<String> exports = <String>[
    ...files,
    'src/internal/i18n.dart',
    'src/theme/color_scheme.dart',
    'src/theme/theme.dart',
    'src/theme/tokens.dart',
    'src/types.dart',
  ]..sort();

  final StringBuffer out = StringBuffer()
    ..writeln('// Generated by `tool/generate.dart`. Do not edit by hand.')
    ..writeln()
    ..writeln('/// Material Design 3 for Flutter, written from the specification and')
    ..writeln('/// extended past it.')
    ..writeln('///')
    ..writeln('/// Nothing here imports `package:flutter/material.dart` or')
    ..writeln('/// `package:flutter/cupertino.dart`. Every component is built on')
    ..writeln('/// `package:flutter/widgets.dart` alone, which is what lets it sit inside a')
    ..writeln('/// Material app, a Cupertino app or a bare [WidgetsApp] without bringing a')
    ..writeln('/// second implementation of Material in behind it, and what makes it')
    ..writeln('/// indifferent to those two libraries moving out of the framework.')
    ..writeln('///')
    ..writeln('/// A component works with no setup: [MPTheme] is an override rather than a')
    ..writeln('/// requirement, and without one the colours follow the platform\'s own')
    ..writeln('/// brightness.')
    ..writeln('///')
    ..writeln('/// ```dart')
    ..writeln("/// import 'package:material_plus_ui/material_plus_ui.dart';")
    ..writeln('///')
    ..writeln("/// MPButton(onPressed: save, child: const Text('Save'))")
    ..writeln('/// ```')
    ..writeln('library;')
    ..writeln();

  for (final String path in exports) {
    if (path == 'src/internal/i18n.dart') {
      out.writeln("export '$path' show MPLocale, registerMPMessages;");
    } else {
      out.writeln("export '$path';");
    }
  }

  return out.toString();
}

/// Every demo, by the name the documentation site asks for it with.
String registry(Directory root) {
  final Directory demos = Directory('${root.path}/example/lib/demos');
  final RegExp widget = RegExp(
    r'^class (\w+) extends (?:StatelessWidget|StatefulWidget)',
    multiLine: true,
  );
  final List<(String key, String import, String name)> entries = <(String, String, String)>[];

  final List<Directory> folders = demos.listSync().whereType<Directory>().toList()
    ..sort((Directory a, Directory b) => a.path.compareTo(b.path));

  for (final Directory folder in folders) {
    final List<File> files =
        folder
            .listSync()
            .whereType<File>()
            .where((File file) => file.path.endsWith('.dart'))
            .toList()
          ..sort((File a, File b) => a.path.compareTo(b.path));

    for (final File file in files) {
      // The first public widget in the file is the demo; private helpers such
      // as a row or a box drawn for the demo may come before it.
      final Match? match = widget
          .allMatches(file.readAsStringSync())
          .where((Match candidate) => !candidate.group(1)!.startsWith('_'))
          .firstOrNull;

      if (match == null) {
        continue;
      }

      final String component = _basename(folder.path).replaceAll('_', '-');
      final String demo = _basename(file.path).replaceAll('.dart', '').replaceAll('_', '-');
      final String import = file.path.substring('${root.path}/example/lib/'.length);

      entries.add(('$component/$demo', import, match.group(1)!));
    }
  }

  final StringBuffer out = StringBuffer()
    ..writeln('// Generated by `tool/generate.dart` from the folders beside it. Do not')
    ..writeln('// edit by hand: add a demo file and run the generator again.')
    ..writeln()
    ..writeln("import 'package:flutter/widgets.dart';")
    ..writeln();

  final List<String> imports =
      entries.map(((String, String, String) entry) => entry.$2).toSet().toList()..sort();

  for (final String import in imports) {
    out.writeln("import 'package:material_plus_ui_example/$import' as ${_alias(import)};");
  }

  out
    ..writeln()
    ..writeln('/// Every demo, by the name the documentation site embeds it under.')
    ..writeln('final Map<String, WidgetBuilder> demos = <String, WidgetBuilder>{');

  for (final (String key, String import, String name) in entries) {
    out.writeln("  '$key': (BuildContext context) => const ${_alias(import)}.$name(),");
  }

  out.writeln('};');

  return out.toString();
}

String _alias(String import) {
  return import
      .replaceAll('demos/', '')
      .replaceAll('.dart', '')
      .replaceAll('/', '_')
      .replaceAll(RegExp('[^a-z0-9_]'), '_');
}

String _basename(String path) => path.split(Platform.pathSeparator).last;
