/**
 * The catalog schema an agent can read, written from the catalog this library runs.
 *
 * `MP_A2UI_CATALOG_ID` is a URL, and a URL that answers nothing is a broken
 * promise: an agent told to target this catalog, or a developer wondering what is
 * in it, has one place to look and it is that address. So the schema is generated
 * into the repository's `docs/public/`, which the documentation site serves at the path the id
 * names — see `src/a2ui/catalog.ts`.
 *
 * ## Generated rather than written
 *
 * A catalog schema is the same statement as the Zod schemas in
 * `src/a2ui/extended/api.ts`, said in JSON Schema. Written by hand it would be a
 * second copy of a contract — and a second copy of a contract is a contract that is
 * wrong, because the copy an agent reads and the copy a renderer enforces drift the
 * first time somebody adds a prop to one of them. This runs in `npm run build` for
 * exactly that reason, and the output is committed so the site can serve it without
 * a build.
 *
 * ## Why it reads `dist/` and not `src/`
 *
 * Because `dist/` is what a consumer resolves. The schemas are plain Zod and would
 * run from source through `tsx`, but then a build that dropped a component — a bad
 * export, a module left out — would still produce a catalog that advertised it. The
 * file is the published description of the published package.
 *
 * ## The SDK writes it, and this checks it
 *
 * From protocol v1.0 a catalog document is something the SDK produces itself:
 * `Catalog.toJson()` writes the components, the functions and the `$defs` they
 * point into, and it is the same document `getRendererCapabilities({ versions:
 * ['1.0'], includeInlineCatalogs: true })` sends an agent that asks what a client
 * can draw. So nothing is converted here. The file is that document, with a
 * `description` that says where it came from and whose schemas are in it, and
 * the catalogs in `src/a2ui/catalog.ts` give the SDK the full address of the
 * protocol's common types to write references against.
 *
 * What is left is the checking, and the build fails on either check. The
 * document has to load back through `Catalog.fromJson` as a v1.0 catalog with
 * the same components and functions, which is what an agent's SDK does with it.
 * And every reference has to land: on a definition the protocol's
 * `common_types.json` has, by its full address, or on something inside this
 * document. A relative `common_types.json` would resolve beside the published
 * file, where the site serves nothing.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { Catalog, V10_STANDARD_DEFS } from '@a2ui/web_core/v1_0';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

/*
 * `@a2ui/react` declares a custom element class as it loads, so outside a
 * browser it stops on `HTMLElement` before anything else runs. This script only
 * reads the schemas and never renders, so an empty class is all it is given:
 * nothing here constructs an element or defines one.
 */
globalThis.HTMLElement ??= class HTMLElement {};

const { MP_A2UI_CATALOG_ID, mpA2uiExtendedCatalog } = await import(
  pathToFileURL(resolve(root, 'dist/a2ui/index.js')).href
);

/*
 * The path comes out of the id rather than being written beside it, so the address
 * an agent is given and the file the site serves cannot disagree. A host this
 * repository does not publish is a mistake worth stopping on: nothing here can
 * serve that id, so the URL in the package would be dead on arrival.
 */
const { host, pathname } = new URL(MP_A2UI_CATALOG_ID);

if (host !== 'material-plus.cdget.com') {
  throw new Error(
    `MP_A2UI_CATALOG_ID points at ${host}, which this repository does not publish. ` +
      'The id has to be a path the documentation site serves, or the catalog it names is unreachable.'
  );
}

// The documentation site sits at the repository root, two levels above this
// package, and serves `docs/public` at `/`.
const out = resolve(root, '../../docs/public', `.${pathname}`);

/** Where the protocol's common types are published, as references name them. */
const COMMON_TYPES = 'https://a2ui.org/specification/v1_0/common_types.json#/$defs/';

const generated = mpA2uiExtendedCatalog.toJson();

/*
 * `catalogId`, `protocolVersion` and `description` first, so the file opens with
 * what it is. `$comment` would be the usual place for the provenance, but the
 * protocol's catalog document admits no key it does not define.
 */
const document = {
  catalogId: generated.catalogId,
  protocolVersion: generated.protocolVersion,
  description:
    "Material Plus's A2UI catalog: the basic catalog's eighteen components drawn as Material " +
    'Design 3, and five of its own for tables, charts and figures. Generated by ' +
    'scripts/build-a2ui-catalog.mjs from src/a2ui; do not edit. The components the basic ' +
    "catalog names keep that project's own schemas (github.com/a2ui-project/a2ui, Apache-2.0); " +
    'the rest are Material Plus (github.com/jooy2/material-plus-ui, MIT).',
  ...generated
};

/*
 * The document read back the way an agent's SDK reads it. `fromJson` refuses a
 * malformed definition and a reference into any document but this one and the
 * common types, and what it loads has to be the catalog that was written.
 */
const sortedKeys = (map) => JSON.stringify([...map.keys()].sort());
/*
 * `@index` and the other `@` functions are the protocol's own and belong to no
 * catalog, so the SDK carries them in the function list and never writes them.
 */
const catalogFunctions = (map) => new Map([...map].filter(([name]) => !name.startsWith('@')));
const loaded = Catalog.fromJson(document);
const differences = [
  loaded.id === MP_A2UI_CATALOG_ID ? null : `its id is ${loaded.id}`,
  loaded.protocolVersion === '1.0' ? null : `its protocol version is ${loaded.protocolVersion}`,
  sortedKeys(loaded.components) === sortedKeys(mpA2uiExtendedCatalog.components)
    ? null
    : 'its components differ',
  sortedKeys(loaded.functions) === sortedKeys(catalogFunctions(mpA2uiExtendedCatalog.functions))
    ? null
    : 'its functions differ'
].filter(Boolean);

if (differences.length > 0) {
  throw new Error(
    `the generated catalog does not load back as the catalog it was written from: ${differences.join('; ')}`
  );
}

/** What a `#/...` pointer lands on inside the document, if anything. */
const pointedAt = (pointer) =>
  pointer
    .slice(2)
    .split('/')
    .map((key) => key.replaceAll('~1', '/').replaceAll('~0', '~'))
    .reduce((node, key) => (node && typeof node === 'object' ? node[key] : undefined), document);

const references = [...JSON.stringify(document).matchAll(/"\$ref":"([^"]*)"/g)].map(
  ([, ref]) => ref
);
const dangling = [...new Set(references)].filter((ref) =>
  ref.startsWith('#/')
    ? pointedAt(ref) === undefined
    : !ref.startsWith(COMMON_TYPES) || !(ref.slice(COMMON_TYPES.length) in V10_STANDARD_DEFS)
);

if (dangling.length > 0) {
  throw new Error(
    `the generated catalog names definitions that do not exist: ${dangling.join(', ')}`
  );
}

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, `${JSON.stringify(document, null, 2)}\n`);

const kb = (bytes) => `${(bytes / 1024).toFixed(1)} kB`;

console.log(
  `a2ui: ${relative(root, out)} ${Object.keys(document.components).length} components, ` +
    `${Object.keys(document.functions ?? {}).length} functions, ${kb(JSON.stringify(document).length)}`
);
